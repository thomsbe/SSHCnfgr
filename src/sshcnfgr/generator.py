from __future__ import annotations

from datetime import datetime
from pathlib import Path

from .model import HostDatabase, HostEntry, HostGroup, get_option_ci
from .paths import GENERATED_CONFIG_PATH, SSH_DIR, ensure_private_dir, set_private_permissions
from .store import create_backup


def _resolve_direct_host_identity_file(host: HostEntry, db: HostDatabase) -> str | None:
    """Loest nur host-eigene Identity-Angaben auf (ohne Gruppen-/Global-Defaults)."""
    if host.identity_file:
        return host.identity_file
    if host.identity:
        profile = db.get_identity_by_name(host.identity)
        if profile and profile.enabled:
            return profile.identity_file
    return None


def _resolve_group_identity_file(group: HostGroup, db: HostDatabase) -> str | None:
    if not group.identity:
        return None
    profile = db.get_identity_by_name(group.identity)
    if profile and profile.enabled:
        return profile.identity_file
    return None


def render_host_block(
    host: HostEntry,
    db: HostDatabase,
    *,
    inline_group_defaults: bool = False,
) -> str:
    lines: list[str] = [f"Host {host.name}"]
    lines.append(f"  HostName {host.host_name}")

    if host.user:
        lines.append(f"  User {host.user}")
    if host.port is not None:
        lines.append(f"  Port {host.port}")

    global_identity_file = get_option_ci(db.global_options, "IdentityFile")
    resolved_identity_file = (
        db.resolve_identity_file(host)
        if inline_group_defaults
        else _resolve_direct_host_identity_file(host, db)
    )
    # Der globale IdentityFile-Default wird schon im Host-*-Block ausgegeben
    # und muss nicht in jeden Host-Block wiederholt werden.
    if resolved_identity_file and resolved_identity_file != global_identity_file:
        lines.append(f"  IdentityFile {resolved_identity_file}")

    for key, value in sorted(host.extra_options.items(), key=lambda item: item[0].lower()):
        lines.append(f"  {key} {value}")

    return "\n".join(lines)


def render_group_match_block(
    group: HostGroup,
    member_aliases: list[str],
    db: HostDatabase,
) -> str | None:
    """Erzeugt einen OpenSSH 'Match originalhost'-Block fuer Gruppen-Defaults."""
    if not member_aliases:
        return None

    option_lines: list[str] = []
    if group.user:
        option_lines.append(f"  User {group.user}")
    if group.port is not None:
        option_lines.append(f"  Port {group.port}")

    global_identity_file = get_option_ci(db.global_options, "IdentityFile")
    group_identity_file = _resolve_group_identity_file(group, db)
    if group_identity_file and group_identity_file != global_identity_file:
        option_lines.append(f"  IdentityFile {group_identity_file}")

    for key, value in sorted(group.extra_options.items(), key=lambda item: item[0].lower()):
        option_lines.append(f"  {key} {value}")

    if not option_lines:
        return None

    header_comment = f"# Gruppe: {group.name}"
    if group.description:
        header_comment += f" ({group.description})"

    aliases_csv = ",".join(sorted(member_aliases, key=str.lower))
    return "\n".join([header_comment, f"Match originalhost {aliases_csv}", *option_lines])


def generate_config(
    db: HostDatabase,
    *,
    include_timestamp: bool = True,
    use_group_match: bool = True,
) -> str:
    header = ["# Generated by sshcnfgr"]
    if include_timestamp:
        header.append(f"# Timestamp: {datetime.now().isoformat(timespec='seconds')}")
    header.append("")

    # Globale Include-Direktiven gehoeren vor den ersten Host-Block, nicht in Host *.
    include_lines: list[str] = []
    wildcard_options: list[tuple[str, str]] = []
    for key, value in sorted(db.global_options.items(), key=lambda item: item[0].lower()):
        if key.lower() == "include":
            include_lines.append(f"{key} {value}")
        else:
            wildcard_options.append((key, value))

    blocks: list[str] = []
    if include_lines:
        blocks.append("\n".join(include_lines))

    # Aktive Hosts sortiert nach ihrer ersten Gruppe (in Nutzer-Gruppenreihenfolge),
    # damit u. a. VS Code Remote-SSH wichtige Gruppen ganz oben anzeigt.
    sections = db.grouped_hosts(enabled_only=True)
    has_named_groups = any(group is not None for group, _ in sections)

    for group, members in sections:
        section_blocks: list[str] = []
        if has_named_groups:
            if group is not None:
                title = f"# === Gruppe: {group.name} ==="
                if group.description:
                    title = f"# === Gruppe: {group.name} ({group.description}) ==="
                section_blocks.append(title)
            else:
                section_blocks.append("# === Ohne Gruppe ===")

        for host in members:
            section_blocks.append(
                render_host_block(host, db, inline_group_defaults=not use_group_match)
            )

        if has_named_groups:
            # Abschnittskommentar direkt ueber den ersten Host-Block setzen.
            first_host = section_blocks[1]
            blocks.append(f"{section_blocks[0]}\n{first_host}")
            blocks.extend(section_blocks[2:])
        else:
            blocks.extend(section_blocks)

    # Gruppen-Defaults als 'Match originalhost'-Bloecke nach den Host-Bloecken
    # (Host-Werte gewinnen vor Gruppen-Defaults, Gruppen-Defaults vor Host *).
    if use_group_match:
        enabled_hosts = [host for host in db.hosts if host.enabled]
        match_blocks: list[str] = []
        for group in db.ordered_groups():
            aliases = [host.name for host in enabled_hosts if group.name in host.groups]
            rendered_match = render_group_match_block(group, aliases, db)
            if rendered_match:
                match_blocks.append(rendered_match)
        if match_blocks:
            blocks.append(f"# === Gruppen-Defaults (Match) ===\n{match_blocks[0]}")
            blocks.extend(match_blocks[1:])

    # OpenSSH verwendet pro Parameter den ersten gefundenen Wert, daher gehoeren
    # globale Defaults (Host *) ans Dateiende, sonst schlagen sie Host-Werte.
    if wildcard_options:
        global_lines = ["Host *"]
        for key, value in wildcard_options:
            global_lines.append(f"  {key} {value}")
        blocks.append("\n".join(global_lines))

    return "\n\n".join(["\n".join(header).rstrip(), *blocks]).strip() + "\n"


def write_generated_config(
    db: HostDatabase,
    output: Path = GENERATED_CONFIG_PATH,
    *,
    backup: bool = True,
) -> Path:
    if output.parent == SSH_DIR:
        ensure_private_dir(output.parent)
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
    if backup:
        create_backup(output)

    content = generate_config(db)

    tmp_path = output.with_name(output.name + ".tmp")
    tmp_path.write_text(content, encoding="utf-8")
    set_private_permissions(tmp_path)
    tmp_path.replace(output)
    return output
